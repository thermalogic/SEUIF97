def cal_solo_coff(IJn,k,m):
    soI=[IJn[0][k]-m]  #  需要独立计算的 i-m 幂次数组
    i2soI=[0]   # 原幂和独立幂数值索引关系数组：数组大小和原幂次大小一样，但是，其中存放的是该位置原幂次在独立幂次数组soI中的位置

    for iitem in range(1,len(IJn)):
        curi=IJn[iitem][k]-m
        if curi not in soI:
            soI.append(curi)
            i2soI.append(len(soI)-1)
        else: 
            i2soI.append(soI.index(curi))   
    
    print(k,"-", m," 独立幂次数量  : ",len(soI))
    print(k,"-",m," 独立幂次: \n ",soI)
    print("原",k,"-",m,"幂次的幂值在使用soI预先计算幂值数组中的位置: \n",i2soI)

    print(f"static const int soI[{len(soI)}] = {{{','.join(map(str, soI))}}};")
    print(f"static const int i2soI[{len(IJn)}] = {{{','.join(map(str, i2soI))}}};")   


